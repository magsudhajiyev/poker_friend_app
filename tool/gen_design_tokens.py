#!/usr/bin/env python3
"""Generate the Final Table v3 token layer for Flutter.

    python3 tool/gen_design_tokens.py           # write the Dart file
    python3 tool/gen_design_tokens.py --check   # exit 1 if it is out of date

Source:  design_tokens/tokens.json — exported from the Final Table design
         system (synced from Figma finaltable_v3). Edit tokens there, never
         in the generated file.
Output:  lib/design_system/tokens/ft_tokens.g.dart

Colours become an `FtColors` ThemeExtension with a `dark` and a `light`
instance (a token may also hold a literal #RRGGBBAA when its alpha is part of
the design, e.g. tab-bar-glass); primitives stay private so screens can only pick semantic or
component tokens. Deprecated `misc-*` aliases are skipped (they never
existed in Dart).
"""

import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "design_tokens", "tokens.json")
OUT = os.path.join(ROOT, "lib", "design_system", "tokens", "ft_tokens.g.dart")
FONT_FAMILY = "42dot Sans"


def camel(name):
    name = name.replace("2xl", "xxl")
    parts = name.split("-")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def px(v):
    v = str(v).strip()
    assert re.fullmatch(r"-?\d+(\.\d+)?(px)?", v), v
    n = float(v.replace("px", ""))
    return f"{n:g}" if n != int(n) else f"{int(n)}"


def doc(text, indent="  "):
    text = re.sub(r"`([^`]*)`", r"`\1`", (text or "").strip())
    return "".join(f"{indent}/// {line}\n" for line in text.splitlines() if line) if text else ""


def hex_color(h):
    h = h.lstrip("#")
    if len(h) == 6:
        h = "FF" + h
    elif len(h) == 8:  # #RRGGBBAA → AARRGGBB
        h = h[6:] + h[:6]
    else:
        raise ValueError(h)
    return f"Color(0x{h.upper()})"


def rgba(s):
    m = re.fullmatch(r"rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)", s.strip())
    r, g, b, a = int(m[1]), int(m[2]), int(m[3]), float(m[4])
    return f"Color(0x{round(a * 255):02X}{r:02X}{g:02X}{b:02X})"


def parse_shadows(value):
    out = []
    for part in re.split(r",\s*(?![^()]*\))", value):
        m = re.fullmatch(r"(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(-?\d+)(?:px)?\s+(.+)", part.strip())
        x, y, blur, spread, col = m.groups()
        col = rgba(col) if col.startswith("rgba") else hex_color(col)
        out.append(f"BoxShadow(color: {col}, offset: Offset({x}, {y}), blurRadius: {blur}, spreadRadius: {spread})")
    return out


def build():
    t = json.load(open(SRC))
    toks = t["color"]["tokens"]
    prims = {x["name"]: x["value"] for x in toks if not isinstance(x["value"], dict)}
    sem = [x for x in toks if isinstance(x["value"], dict)
           and not x["name"].startswith("misc-")
           and not (x.get("usage") or "").startswith("Deprecated")]
    by_name = {x["name"]: x for x in toks}

    def resolve(ref, mode, depth=0):
        assert depth < 10, ref
        m = re.fullmatch(r"\{([a-z0-9-]+)\}", ref)
        if not m:
            return ref
        n = m[1]
        if n in prims:
            return n
        return resolve(by_name[n]["value"][mode], mode, depth + 1)

    L = []
    w = L.append
    w("// GENERATED by tool/gen_design_tokens.py from design_tokens/tokens.json.\n")
    w("// Do not edit by hand — change the tokens, then re-run the generator.\n")
    w(f"// Source: {t['meta'].get('file', 'Figma finaltable_v3')} · synced {t['meta'].get('synced', '')}\n")
    w("// ignore_for_file: constant_identifier_names, lines_longer_than_80_chars, unused_field, unused_element\n\n")
    w("import 'package:flutter/material.dart';\n\n")

    # ---- Primitives (private)
    w("/// Raw palette. Private on purpose: build UI from [FtColors] only.\n")
    w("abstract final class _P {\n")
    for n, v in prims.items():
        w(f"  static const Color {camel(n)} = {hex_color(v)};\n")
    w("}\n\n")

    # ---- Public data colours (same in both themes)
    w("/// Opponent tag colours (ColorSwatch). Data colours: identical in both\n")
    w("/// themes and never used for UI chrome.\n")
    w("abstract final class FtTagColors {\n")
    tags = [n for n in prims if n.startswith("tag-")]
    for n in tags:
        w(doc(by_name[n].get("usage")))
        w(f"  static const Color {camel(n[4:])} = _P.{camel(n)};\n")
    w("\n  /// All tag colours in picker order.\n")
    w("  static const List<Color> all = [" + ", ".join(camel(n[4:]) for n in tags) + "];\n")
    w("}\n\n")
    w("/// Brand colours that are not UI tokens.\n")
    w("abstract final class FtBrand {\n")
    w(doc(by_name["brand-mark"].get("usage")))
    w("  static const Color mark = _P.brandMark;\n}\n\n")

    # ---- FtColors theme extension
    w("/// Final Table v3 colour tokens — semantic (`label`, `bg`, `fill`, `text`, …)\n")
    w("/// and component (`button`, `textfield`, `toggle`, `focus`) tiers.\n")
    w("///\n/// Read with `FtColors.of(context)` or `context.ftColors`. The app ships\n")
    w("/// [FtColors.dark]; [FtColors.light] must keep working.\n")
    w("@immutable\nclass FtColors extends ThemeExtension<FtColors> {\n")
    w("  const FtColors({\n")
    for x in sem:
        w(f"    required this.{camel(x['name'])},\n")
    w("  });\n\n")
    for x in sem:
        w(doc(x.get("usage")))
        w(f"  final Color {camel(x['name'])};\n\n")
    for mode in ("dark", "light"):
        w(f"  /// The {mode.capitalize()} theme.\n")
        w(f"  static const FtColors {mode} = FtColors(\n")
        for x in sem:
            ref = x["value"][mode]
            prim = resolve(ref, mode)
            if prim not in prims:
                # A literal colour (e.g. #fafafa08: alpha baked into the token).
                assert re.fullmatch(r"#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?", prim), (x["name"], ref)
                w(f"    {camel(x['name'])}: {hex_color(prim)},\n")
                continue
            via = "" if ref == "{" + prim + "}" else f" // via {ref[1:-1]}"
            w(f"    {camel(x['name'])}: _P.{camel(prim)},{via}\n")
        w("  );\n\n")
    w("  /// The tokens for the current theme; falls back to [dark].\n")
    w("  static FtColors of(BuildContext context) =>\n")
    w("      Theme.of(context).extension<FtColors>() ?? dark;\n\n")
    w("  @override\n  FtColors copyWith({\n")
    for x in sem:
        w(f"    Color? {camel(x['name'])},\n")
    w("  }) {\n    return FtColors(\n")
    for x in sem:
        c = camel(x["name"])
        w(f"      {c}: {c} ?? this.{c},\n")
    w("    );\n  }\n\n")
    w("  @override\n  FtColors lerp(covariant ThemeExtension<FtColors>? other, double t) {\n")
    w("    if (other is! FtColors) return this;\n    return FtColors(\n")
    for x in sem:
        c = camel(x["name"])
        w(f"      {c}: Color.lerp({c}, other.{c}, t)!,\n")
    w("    );\n  }\n}\n\n")
    w("extension FtColorsContext on BuildContext {\n")
    w("  /// Shorthand for `FtColors.of(context)`.\n")
    w("  FtColors get ftColors => FtColors.of(this);\n}\n\n")

    # ---- Dimension families
    def dim_class(cls, key, prefix, docline, rename=None):
        w(f"/// {docline}\n")
        w(f"abstract final class {cls} {{\n")
        for x in t[key]["tokens"]:
            n = x["name"][len(prefix):]
            n = rename(n) if rename else camel(n)
            w(doc(x.get("usage")))
            w(f"  static const double {n} = {px(x['value'])};\n")
        w("}\n\n")

    dim_class("FtSpacing", "spacing", "spacing-", "Spacing scale, named by pixel value (`s16` = 16).",
              lambda n: "s" + n)
    dim_class("FtRadius", "radius", "radius-", "Corner radii.")
    dim_class("FtSize", "size", "size-", "Icon sizes and the 44pt minimum hit target.")
    dim_class("FtBorderWidth", "borderWidth", "border-width-", "Stroke widths.")
    w("/// Opacity applied on top of a colour token.\n")
    w("abstract final class FtOpacity {\n")
    for x in t["opacity"]["tokens"]:
        w(doc(x.get("usage")))
        w(f"  static const double {camel(x['name'][len('opacity-'):])} = {x['value']};\n")
    w("}\n\n")

    # ---- Shadows
    w("/// Elevation shadows (neutral black). The focus ring follows the theme,\n")
    w("/// so build it from `FtColors.focusRing` with [FtShadows.focusRing].\n")
    w("abstract final class FtShadows {\n")
    for x in t["shadow"]["tokens"]:
        if isinstance(x["value"], dict):
            continue
        w(doc(x.get("usage")))
        items = ",\n    ".join(parse_shadows(x["value"]))
        w(f"  static const List<BoxShadow> {camel(x['name'])} = [\n    {items},\n  ];\n\n")
    w("  /// 3px focus ring in the theme's `focusRing` colour.\n")
    w("  static List<BoxShadow> focusRing(FtColors c) => [\n")
    w("        BoxShadow(color: c.focusRing, spreadRadius: FtBorderWidth.focus),\n      ];\n}\n\n")

    # ---- Typography
    w(f"/// Text styles — Apple's text-style ramp set in {FONT_FAMILY}.\n")
    w("///\n/// Styles carry no colour: apply a `label*`/`text*` token with\n")
    w("/// `.copyWith(color: …)`. Figures that update or line up use `.tabular`.\n")
    w("abstract final class FtTextStyles {\n")
    w(f"  static const String fontFamily = '{FONT_FAMILY}';\n\n")
    for g in t["type"]["groups"]:
        for s in g["styles"]:
            size = float(px(s["fontSize"]))
            lh = float(px(s["lineHeight"]))
            w(doc(f"{px(s['fontSize'])}/{px(s['lineHeight'])} · {s['fontWeight']}. {s.get('usage', '')}"))
            w(f"  static const TextStyle {camel(s['name'])} = TextStyle(\n")
            w("    fontFamily: fontFamily,\n")
            w(f"    fontSize: {px(s['fontSize'])},\n")
            w(f"    height: {lh / size:.4f}, // {px(s['lineHeight'])}px line\n")
            w(f"    fontWeight: FontWeight.w{s['fontWeight']},\n")
            w(f"    letterSpacing: {px(s['letterSpacing'])},\n")
            w("    leadingDistribution: TextLeadingDistribution.even,\n")
            w("  );\n\n")
    w("}\n\n")
    w("extension FtTextStyleX on TextStyle {\n")
    w("  /// Tabular (fixed-width) figures for amounts, timers and stat columns.\n")
    w("  TextStyle get tabular =>\n")
    w("      copyWith(fontFeatures: const [FontFeature.tabularFigures()]);\n}\n\n")
    return "".join(L)


def main():
    out = build()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != out:
            print("ft_tokens.g.dart is out of date — run python3 tool/gen_design_tokens.py")
            sys.exit(1)
        print("ft_tokens.g.dart is up to date")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(out)
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
